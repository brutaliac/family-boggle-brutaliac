'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const net=require('node:net');
test('admin merge authenticates, rejects stale requests, archives and persists records',async t=>{
 const port=await new Promise(resolve=>{const s=net.createServer();s.listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'boggle-admin-'));
 const player=(name,points)=>({name,games:2,wins:1,points,words:10,bestScore:points,mostWords:8,bestStreak:1,longestWord:points>20?'longer':'short'});
 fs.writeFileSync(path.join(dir,'stats.json'),JSON.stringify({version:1,updatedAt:1,rooms:{family:{players:{bob:player('Bob',20),bobby:player('Bobby',30)},aliases:{robert:'bobby'}}}}));
 const child=spawn(process.execPath,['server.js'],{cwd:path.join(__dirname,'..'),env:{...process.env,PORT:String(port),DATA_DIR:dir,GITHUB_TOKEN:'',BOGGLE_ADMIN_PASSWORD:'test-secret'},stdio:['ignore','pipe','pipe']});
 t.after(async()=>{child.kill();await new Promise(r=>child.exitCode!==null?r():child.once('exit',r));fs.rmSync(dir,{recursive:true,force:true});});
 await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('startup timeout')),10000);child.stdout.on('data',d=>{if(d.toString().includes('listening')){clearTimeout(timer);resolve();}});child.once('error',reject);});
 const call=(route,body,password='test-secret')=>fetch(`http://127.0.0.1:${port}/api/admin/${route}`,{method:body?'POST':'GET',headers:{Authorization:'Bearer '+password,'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});
 assert.equal((await call('players',null,'wrong')).status,401);
 assert.equal((await fetch(`http://127.0.0.1:${port}/admin`)).status,200);
 const body={room:'family',source:'bobby',target:'bob',updatedAt:1};
 assert.equal((await call('merge',{...body,source:'bob'})).status,400);
 assert.equal((await call('merge',{...body,updatedAt:0})).status,409);
 assert.equal((await call('merge',body)).status,200);
 const saved=JSON.parse(fs.readFileSync(path.join(dir,'stats.json'))).rooms.family;
 assert.equal(saved.players.bob.points,50);assert.equal(saved.players.bob.games,4);assert.equal(saved.players.bob.bestScore,30);assert.equal(saved.players.bob.longestWord,'longer');
 assert.equal(saved.players.bobby,undefined);assert.equal(saved.aliases.bobby,'bob');assert.equal(saved.aliases.robert,'bob');assert.equal(saved.mergeHistory[0].source.points,30);assert.equal(saved.mergeHistory[0].target.points,20);
 assert.equal((await call('players').then(r=>r.json())).rooms[0].players.length,1);
 assert.equal((await call('merge',body)).status,400);
});
